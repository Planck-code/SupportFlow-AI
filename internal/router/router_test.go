package router

import (
	"bytes"
	"encoding/json"
	"log/slog"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
)

func TestHealthz(t *testing.T) {
	var logs bytes.Buffer
	r := New(slog.New(slog.NewJSONHandler(&logs, nil)))
	req := httptest.NewRequest(http.MethodGet, "/healthz?token=private-query", nil)
	req.Header.Set("Authorization", "Bearer private-header")
	req.Header.Set("X-Request-ID", "untrusted-id")
	w := httptest.NewRecorder()
	r.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", w.Code)
	}
	if w.Body.String() != `{"status":"ok"}` {
		t.Fatalf("body = %q, want health JSON", w.Body.String())
	}
	if got := w.Header().Get("Content-Type"); !strings.HasPrefix(got, "application/json") {
		t.Fatalf("Content-Type = %q, want application/json", got)
	}
	id := w.Header().Get("X-Request-ID")
	if id == "" || id == "untrusted-id" {
		t.Fatalf("request ID must be generated by the server, got %q", id)
	}
	var entry struct {
		RequestID string `json:"request_id"`
		Status    int    `json:"status"`
		Route     string `json:"route"`
	}
	if err := json.Unmarshal(logs.Bytes(), &entry); err != nil {
		t.Fatalf("invalid JSON request log: %v", err)
	}
	if entry.RequestID != id || entry.Status != 200 || entry.Route != "/healthz" {
		t.Fatalf("unexpected request log: %+v", entry)
	}
	if strings.Contains(logs.String(), "private-") {
		t.Fatal("request log contains sensitive header or query")
	}
}

func TestUnknownRouteDoesNotLogBodyOrRawPath(t *testing.T) {
	var logs bytes.Buffer
	r := New(slog.New(slog.NewJSONHandler(&logs, nil)))
	req := httptest.NewRequest(http.MethodPost, "/private-path", strings.NewReader("private-body"))
	w := httptest.NewRecorder()
	r.ServeHTTP(w, req)
	if w.Code != http.StatusNotFound {
		t.Fatalf("status = %d, want 404", w.Code)
	}
	if strings.Contains(logs.String(), "private-") {
		t.Fatal("request log contains raw path or body")
	}
}
